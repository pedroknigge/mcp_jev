function writeFixture(dir: string): void {
  const files: Record<string, string> = {
    ".gitignore": "secret.bin\nignored-dir/\n",
    "README.md": "# fixture\n",
    "src/billing/invoice.ts": [
      'import { money } from "./money";',
      'import { fmt } from "../fmt";',
      "export function total(n: number) {",
      "  if (n > 0) return n;",
      "  return 0;",
      "}",
      "",
    ].join("\n"),
    "src/auth/login.ts": ['import { jwt } from "./jwt";', "export function login() { return jwt; }", ""].join("\n"),
    "src/auth/login.test.ts": [
      'import { test } from "node:test";',
      'import { login } from "./login";',
      'test("login", () => { login(); });',
      "",
    ].join("\n"),
    "db/migrations/001_init.sql": "CREATE TABLE invoices (id int);\n",
    "generated/out.ts": "export const generated = 1;\n",
    "node_modules/pkg/index.js": "module.exports = 1;\n",
    "package-lock.json": "{}\n",
    "photo.png": "not-really-an-image",
    "secret.bin": "secret",
    "ignored-dir/skip.ts": "export const nope = 1;\n",
    "src/generated_header.ts": "// @generated by tool\nexport const z = 1;\n",
    "dist/bundle.js": "console.log(1);\n",
  };
  for (const [rel, body] of Object.entries(files)) {
    const full = path.join(dir, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, body);
  }
}

function runCli(args: string[], extraEnv: NodeJS.ProcessEnv, entry = "src/index.ts") {
  return spawnSync(process.execPath, ["--import", "tsx", entry, ...args], {
    cwd: root,
    encoding: "utf8",
    env: { ...process.env, TYPESAFE_API_KEY: "", ...extraEnv },
  });
}

