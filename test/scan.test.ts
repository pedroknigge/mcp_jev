test("runScan Pass 1 + Pass 2 reuse handleRunPack with a mocked systemOne", async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "mcp-jev-scan-live-"));
  writeFixture(dir);
  const config = loadConfig({ TYPESAFE_API_KEY: "test-key" }, { readUserStore: false });
  const states: unknown[] = [];
  const { records, summary } = await runScan({
    root: dir,
    concurrency: 3,
    pass2: 2,
    config,
    systemOne: async (input) => {
      states.push(input.state);
      const pathName = String((input.state as { path?: string }).path ?? "");
      const excerpt = (input.state as { excerpt?: string }).excerpt;
      assert.equal(input.questions.primary_concern?.type, "choice");
      assert.equal(input.questions.hotspot_file, undefined);
      if (excerpt !== undefined) {
        assert.ok(excerpt.length <= MAX_EXCERPT_CHARS);
      }
      const severity = pathName.includes("billing") ? 2.4 : pathName.includes("auth/login.ts") ? 1.8 : 0.4;
      const concern = pathName.includes("billing") ? "verification" : "none";
      return {
        model: "jev-latest",
        answers: fakeAnswers(severity, concern),
        usage: { input_tokens: 4, output_tokens: 2 },
      } as SystemOneResult<Questions>;
    },
    writeLine: () => undefined,
    writeSummary: () => undefined,
    writeProgress: () => undefined,
  });

  const pass1 = records.filter((record) => record.pass === 1);
  const pass2 = records.filter((record) => record.pass === 2);
  assert.ok(pass1.length >= 4);
  assert.equal(pass2.length, 2);
  assert.ok(pass1.every((record) => !record.error));
  assert.ok(
    states.some((state) => {
      const rec = state as { excerpt?: string; signals?: { touches_migration?: boolean } };
      return rec.excerpt === undefined && rec.signals && !("touches_migration" in rec.signals);
    }),
  );
  assert.ok(states.some((state) => typeof (state as { excerpt?: string }).excerpt === "string"));
  assert.ok(summary.hottest_paths[0]?.includes("billing") || summary.top_severity[0]?.problem_severity === 2.4);
  assert.ok(summary.primary_concern.verification >= 1);
  assert.match(formatSummaryTable(summary), /Top severity/);
  assert.equal(problemSeverity(pass1.find((r) => r.path.includes("billing"))?.answers), 2.4);
  assert.equal(primaryConcern(pass1.find((r) => r.path.includes("billing"))?.answers), "verification");
});

