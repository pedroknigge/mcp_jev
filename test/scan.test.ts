test("signal extraction: imports, loc, complexity, path heuristics, nearby tests", () => {
  const invoice = [
    'import { money } from "./money";',
    'import fs from "node:fs";',
    "export function total(n: number) {",
    "  if (n > 0 && n < 10) return n;",
    "  return 0;",
    "}",
  ].join("\n");
  const all = ["src/billing/invoice.ts", "src/billing/invoice.test.ts", "src/auth/login.ts"];
  const signals = extractSignals("src/billing/invoice.ts", invoice, all);
  assert.equal(signals.loc, 6);
  assert.ok(signals.import_count >= 2);
  assert.ok(signals.top_imports.includes("money"));
  assert.ok(signals.top_imports.includes("node:fs") || signals.top_imports.includes("fs"));
  assert.equal(signals.has_tests_nearby, true);
  assert.equal(signals.touches_money, true);
  assert.equal(signals.touches_auth, false);
  assert.equal(signals.touches_migration, false);
  assert.equal(signals.is_generated, false);
  assert.ok(signals.complexity_heuristic >= 1);

  assert.deepEqual(pathHeuristics("src/auth/session.ts"), {
    touches_money: false,
    touches_auth: true,
    touches_migration: false,
  });
  assert.deepEqual(pathHeuristics("db/migrations/001.sql"), {
    touches_money: false,
    touches_auth: false,
    touches_migration: true,
  });
  assert.equal(inferLanguage("src/a.ts"), "ts");
  assert.equal(inferLanguage("db/x.sql"), "sql");
  assert.equal(inferRoleHint("src/billing/invoice.ts"), "domain");
  assert.equal(inferRoleHint("src/auth/login.ts"), "infra");
  assert.equal(inferRoleHint("src/auth/login.test.ts"), "test");
  assert.equal(inferRoleHint("db/migrations/001.sql"), "db");
  assert.ok(extractImports("from pathlib import Path\nimport os\n").includes("pathlib"));
  assert.ok(extractImports("from pathlib import Path\nimport os\n").includes("os"));
  assert.ok(complexityHeuristic("if (a) { for (x of y) {} }") >= 2);
});

